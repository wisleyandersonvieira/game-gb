-- Este arquivo é UMA migração só:
--   20260929190000_jornadas.sql
--
-- O QUE MUDA PARA QUEM JÁ USA (nada de comportamento):
--   * Cada combinação de entrada e saída que já existe na conta vira uma
--     jornada com os sete dias iguais, nome automático ("08:00–17:00"), e as
--     pessoas ficam vinculadas a ela. Saída em branco (que valia entrada +
--     8h20) é gravada por extenso. Quem estava sem horário fica sem jornada.
