-- ---------------------------------------------------------------------------
-- 3. A meta de um dia: UMA ordem só, escrita UMA vez
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.meta_do_dia(p_lojaid integer, p_dia date)
RETURNS TABLE (valormeta numeric, pontospremio integer, origem text, descricao text)
LANGUAGE sql
STABLE
SET search_path = public, pg_temp
AS $$
  -- A ordem das três origens (30/09/2026): 1º a especial da data, 2º a meta
  -- daquele dia naquele mês, 3º o modelo do dia da semana. Toda tela e todo
  -- lançamento perguntam AQUI; não repita esta ordem em outro lugar.
  SELECT x.valormeta, x.pontospremio, x.origem, x.descricao
    FROM (
      SELECT me.valormeta, me.pontospremio, 'especial'::text AS origem, me.descricao::text AS descricao, 1 AS ordem
        FROM public.metasespeciais me
       WHERE me.lojaid = p_lojaid AND me.data = p_dia
      UNION ALL
      SELECT md.valormeta, md.pontospremio, 'mes', NULL::text, 2
        FROM public.metasdodia md
       WHERE md.lojaid = p_lojaid AND md.data = p_dia
      UNION ALL
      SELECT mm.valormeta, mm.pontospremio, 'semana', mm.nomedia::text, 3
        FROM public.metasdiariasmodelos mm
       WHERE mm.lojaid = p_lojaid AND mm.diasemanaid = extract(dow FROM p_dia)::integer + 1
    ) x
   ORDER BY x.ordem
   LIMIT 1
$$;

