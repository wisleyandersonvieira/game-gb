-- O gatilho: registra só quando o VALOR ou os PONTOS mudam (salvar de novo o
-- mesmo valor, ou mudar só o nome, não entra).
CREATE OR REPLACE FUNCTION public.registrar_mudanca_de_meta()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_antes  jsonb := CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) END;
  v_depois jsonb := CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) END;
  r        jsonb := coalesce(CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) END, to_jsonb(OLD));
  v_tipo   text;
  v_ref    text;
  v_campo  text := 'valormeta';
BEGIN
  IF TG_TABLE_NAME = 'metasprincipais' THEN
    v_tipo := 'mes'; v_campo := 'valormetatotal';
    v_ref := 'Meta do mês ' || to_char((r->>'datainicio')::date, 'MM/YYYY');
  ELSIF TG_TABLE_NAME = 'metasdodia' THEN
    v_tipo := 'dia';
    v_ref := 'Meta do dia ' || to_char((r->>'data')::date, 'DD/MM/YYYY');
  ELSIF TG_TABLE_NAME = 'metasdiariasmodelos' THEN
    v_tipo := 'semana';
    v_ref := 'Modelo de ' || (ARRAY['domingo', 'segunda', 'terça', 'quarta', 'quinta', 'sexta', 'sábado'])[(r->>'diasemanaid')::integer];
  ELSE
    v_tipo := 'especial';
    v_ref := 'Meta especial ' || to_char((r->>'data')::date, 'DD/MM/YYYY') || ' (' || (r->>'descricao') || ')';
  END IF;
  IF (v_antes->>v_campo)::numeric IS NOT DISTINCT FROM (v_depois->>v_campo)::numeric
     AND (v_antes->>'pontospremio')::integer IS NOT DISTINCT FROM (v_depois->>'pontospremio')::integer THEN
    RETURN NULL;
  END IF;
  INSERT INTO public.metasalteracoes (contaid, lojaid, tipo, referencia, valorantes, valordepois,
                                      pontosantes, pontosdepois, alteradopor)
  VALUES ((r->>'contaid')::integer, (r->>'lojaid')::integer, v_tipo, v_ref,
          (v_antes->>v_campo)::numeric, (v_depois->>v_campo)::numeric,
          (v_antes->>'pontospremio')::integer, (v_depois->>'pontospremio')::integer, auth.uid());
  RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION public.registrar_mudanca_de_meta() FROM public, anon, authenticated;
DROP TRIGGER IF EXISTS metasprincipais_historico ON public.metasprincipais;
CREATE TRIGGER metasprincipais_historico AFTER INSERT OR UPDATE OR DELETE ON public.metasprincipais
