--   afastado. Meta do mes: ligado e ativo quando bateu.
-- - Correcao: deixou de bater -> estorno automatico de quem recebeu;
--   voltou a bater -> paga de novo. Bonus de meta fora do ranking e da nota.
-- - TV: so porcentagem, a menos que a loja ligue "mostrar valores".

