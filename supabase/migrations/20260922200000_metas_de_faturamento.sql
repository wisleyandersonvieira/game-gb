-- - Meta do dia: valor fixo por dia da semana, por loja; "meta especial"
--   para uma data substitui o modelo daquele dia. A meta fica guardada no
--   lancamento (mudar o modelo depois nao muda dias passados).
-- - Lancamento: total vendido no dia (substitui); correcao exige motivo;
--   so o mes atual e o anterior; tudo no historico (quem, quando, antigo,
