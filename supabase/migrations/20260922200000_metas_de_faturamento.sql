-- A meta de um dia: a especial daquela data, se houver; senao, o modelo do
-- dia da semana (1 = domingo ... 7 = sabado). Roda com a RLS de quem chama.
CREATE OR REPLACE FUNCTION public.meta_do_dia(p_lojaid integer, p_dia date)
RETURNS TABLE (valormeta numeric, pontospremio integer, origem text, descricao text)
LANGUAGE sql
STABLE
SET search_path = public, pg_temp
AS $$
  SELECT x.valormeta, x.pontospremio, x.origem, x.descricao
    FROM (
      SELECT me.valormeta, me.pontospremio, 'especial'::text AS origem, me.descricao::text AS descricao, 1 AS ordem
        FROM public.metasespeciais me
       WHERE me.lojaid = p_lojaid AND me.data = p_dia
      UNION ALL
      SELECT mm.valormeta, mm.pontospremio, 'semana', mm.nomedia::text, 2
        FROM public.metasdiariasmodelos mm
       WHERE mm.lojaid = p_lojaid AND mm.diasemanaid = extract(dow FROM p_dia)::integer + 1
    ) x
   ORDER BY x.ordem
   LIMIT 1
$$;

