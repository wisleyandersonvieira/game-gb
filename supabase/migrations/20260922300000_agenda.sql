-- Etapa 1.9 (antiga Fase 9): agenda por loja.
-- Decisoes do Wisley em 22/09/2026, registradas em docs/PLANO_MIGRACAO.md.
--
-- - Agendamento por loja; responsavel = responsavel da loja ou outro que
--   trabalhe nela. Situacoes: Confirmado -> Realizado (pode voltar com
--   motivo) ou -> Cancelado (motivo obrigatorio, final). Nada se apaga.
-- - Pagamento: Pendente / Sinal pago / Pago, com valor opcional.
-- - A tarefa "Atender agendamento" acompanha: remarcou, muda de dia; trocou
--   o responsavel, muda de pessoa; cancelou, e encerrada.
-- - Historico de tudo (quem, quando, antes e depois), que nunca muda.
-- - Anexos no Storage, pasta privada <conta>/<loja>/<agendamento>/.
-- - Na TV so hora e tipo; nome, CPF, telefone, observacoes e valor nunca
--   saem do banco para a TV.
-- - WhatsApp (1.13): campos prontos, nada e enviado.

