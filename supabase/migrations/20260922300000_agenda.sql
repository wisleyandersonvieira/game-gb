-- Texto da tarefa: "15:00 — Aniversario". Nunca leva dados do cliente.
CREATE OR REPLACE FUNCTION public.texto_da_tarefa_agenda(p_dataevento timestamptz, p_tipo text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
  SELECT to_char(p_dataevento AT TIME ZONE 'America/Sao_Paulo', 'HH24:MI') || ' — ' || p_tipo
$$;

