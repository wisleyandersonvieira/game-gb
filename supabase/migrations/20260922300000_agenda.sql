-- Nada se apaga; situacao so pelas transicoes permitidas, para todo caminho.
CREATE OR REPLACE FUNCTION public.valida_agendamento()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Agendamento não se apaga; cancele com motivo.' USING ERRCODE = 'restrict_violation';
  END IF;
  IF NEW.statusagendamento IS DISTINCT FROM OLD.statusagendamento AND NOT (
       (OLD.statusagendamento = 'Confirmado' AND NEW.statusagendamento IN ('Realizado', 'Cancelado'))
    OR (OLD.statusagendamento = 'Realizado'  AND NEW.statusagendamento = 'Confirmado')) THEN
    RAISE EXCEPTION 'Não é possível passar de "%" para "%".', OLD.statusagendamento, NEW.statusagendamento
      USING ERRCODE = 'check_violation';
  END IF;
  IF OLD.statusagendamento = 'Cancelado' THEN
    RAISE EXCEPTION 'Agendamento cancelado não muda mais.' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.contaid IS DISTINCT FROM OLD.contaid OR NEW.lojaid IS DISTINCT FROM OLD.lojaid THEN
    RAISE EXCEPTION 'O agendamento não muda de loja.' USING ERRCODE = 'restrict_violation';
  END IF;
  NEW.atualizadoem := now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER agendamentos_valida
  BEFORE UPDATE OR DELETE ON public.agendamentos
  FOR EACH ROW EXECUTE FUNCTION public.valida_agendamento();

-- A tarefa ligada a um agendamento so nasce e muda pelas funcoes da agenda
-- (senao remarcar e cancelar ficariam dessincronizados).
CREATE OR REPLACE FUNCTION public.protege_tarefa_da_agenda()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE marca varchar(40);
BEGIN
  IF coalesce(current_setting('gamegb.agenda', true), '') = 'sim' THEN
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  END IF;
  IF TG_OP = 'INSERT' THEN
    SELECT sistema INTO marca FROM public.tarefas WHERE tarefaid = NEW.tarefaid;
    IF NEW.agendamentoid IS NOT NULL OR marca = 'modelo_agendamento' THEN
      RAISE EXCEPTION 'A tarefa de atender agendamento nasce sozinha, ao criar o agendamento.' USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
  END IF;
  IF OLD.agendamentoid IS NOT NULL OR (TG_OP = 'UPDATE' AND NEW.agendamentoid IS DISTINCT FROM OLD.agendamentoid) THEN
    RAISE EXCEPTION 'Esta tarefa acompanha um agendamento: mude pela Agenda.' USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

CREATE TRIGGER tarefasatribuidas_da_agenda
  BEFORE INSERT OR UPDATE OR DELETE ON public.tarefasatribuidas
  FOR EACH ROW EXECUTE FUNCTION public.protege_tarefa_da_agenda();

