-- Confere o responsavel: trabalha na loja (vinculo ativo) e esta ativo.
CREATE OR REPLACE FUNCTION public.responsavel_valido(p_contaid integer, p_lojaid integer, p_funcionarioid integer)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.funcionarioslojas fl
      JOIN public.funcionarios f ON f.funcionarioid = fl.funcionarioid AND f.contaid = fl.contaid
     WHERE fl.contaid = p_contaid AND fl.lojaid = p_lojaid AND fl.funcionarioid = p_funcionarioid
       AND fl.ativo AND f.ativo)
$$;

CREATE OR REPLACE FUNCTION public.registra_agenda(
  p_contaid integer, p_lojaid integer, p_agendamentoid integer, p_acao text,
