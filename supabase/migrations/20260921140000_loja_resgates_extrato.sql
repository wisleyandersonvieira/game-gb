-- Le a taxa ponto -> real da conta. NULL se nao estiver configurada direito.
CREATE OR REPLACE FUNCTION public.taxa_da_conta(p_contaid integer)
RETURNS numeric
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE v_texto text; v_taxa numeric;
BEGIN
  SELECT valor INTO v_texto FROM public.configuracoes
   WHERE contaid = p_contaid AND chave = 'TAXA_CONVERSAO_PONTO_REAL';
  BEGIN
    v_taxa := nullif(replace(btrim(coalesce(v_texto, '')), ',', '.'), '')::numeric;
  EXCEPTION WHEN others THEN
    v_taxa := NULL;
  END;
  RETURN CASE WHEN v_taxa > 0 THEN v_taxa END;
END;
$$;

