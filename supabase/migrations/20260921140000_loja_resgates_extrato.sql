$$;

-- ===========================================================================
-- 1. O livro de movimentos (nivel conta; a loja e opcional).
--    Toda entrada e toda saida de pontos vira uma linha aqui, que NUNCA e
--    alterada nem apagada. O saldo e a soma destas linhas.
-- ===========================================================================

CREATE TABLE public.movimentospontos (
  movimentoid   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contaid       integer NOT NULL DEFAULT public.minha_conta() REFERENCES public.contas(contaid) ON DELETE RESTRICT,
  funcionarioid integer NOT NULL,
  lojaid        integer,
  datamovimento timestamptz NOT NULL DEFAULT now(),
  tipo          varchar(30) NOT NULL CHECK (tipo IN (
                  'aprovacao', 'estorno_entrega', 'bonus',
                  'resgate', 'cancelamento_resgate', 'estorno_resgate',
                  'ajuste_abertura')),
  pontos        integer NOT NULL CHECK (pontos <> 0),
  descricao     text NOT NULL,
  entregaid     integer,
  resgateid     integer,
  criadopor     uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  CONSTRAINT movimentospontos_funcionario_fk FOREIGN KEY (contaid, funcionarioid)
    REFERENCES public.funcionarios (contaid, funcionarioid) ON DELETE RESTRICT,
  CONSTRAINT movimentospontos_loja_fk FOREIGN KEY (contaid, lojaid)
    REFERENCES public.lojas (contaid, lojaid) ON DELETE RESTRICT,
  CONSTRAINT movimentospontos_entrega_fk FOREIGN KEY (contaid, entregaid)
    REFERENCES public.entregas (contaid, entregaid) ON DELETE RESTRICT,
  CONSTRAINT movimentospontos_resgate_fk FOREIGN KEY (contaid, resgateid)
    REFERENCES public.resgates (contaid, resgateid) ON DELETE RESTRICT
);

CREATE INDEX movimentospontos_contaid_idx ON public.movimentospontos (contaid);
CREATE INDEX movimentospontos_lojaid_idx  ON public.movimentospontos (lojaid);
CREATE INDEX movimentospontos_extrato_idx ON public.movimentospontos (funcionarioid, datamovimento, movimentoid);

ALTER TABLE public.movimentospontos ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.movimentospontos FROM anon, authenticated;
GRANT SELECT ON public.movimentospontos TO authenticated;
GRANT ALL ON public.movimentospontos TO service_role;
CREATE POLICY movimentospontos_sel ON public.movimentospontos FOR SELECT TO authenticated
  USING (contaid = (select public.minha_conta()));

-- Nunca se altera nem se apaga um movimento: corrige-se com outro movimento.
CREATE OR REPLACE FUNCTION public.movimento_e_imutavel()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  RAISE EXCEPTION 'Movimento de pontos não pode ser alterado nem apagado. Registre outro movimento.'
    USING ERRCODE = 'restrict_violation';
END;
$$;

CREATE TRIGGER movimentospontos_imutavel
  BEFORE UPDATE OR DELETE ON public.movimentospontos
  FOR EACH ROW EXECUTE FUNCTION public.movimento_e_imutavel();

-- ===========================================================================
-- 2. O UNICO caminho que altera o saldo: gravar um movimento.
--    Este gatilho soma o movimento em saldopontos (e em pontostotal, quando e
--    ponto ganho). Ele avisa que e ele quem esta mexendo, e o protetor abaixo
--    so deixa passar alteracao de saldo que venha daqui.
-- ===========================================================================

CREATE OR REPLACE FUNCTION public.aplica_movimento_no_saldo()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_linhas integer;
BEGIN
  PERFORM set_config('gamegb.aplicando_movimento', 'sim', true);

  UPDATE public.funcionarios
     SET saldopontos = saldopontos + NEW.pontos,
         pontostotal = coalesce(pontostotal, 0)
                       + CASE WHEN NEW.tipo IN ('aprovacao', 'estorno_entrega', 'bonus') THEN NEW.pontos ELSE 0 END
   WHERE funcionarioid = NEW.funcionarioid AND contaid = NEW.contaid;
  -- Guardado antes do PERFORM seguinte, que sobrescreveria o FOUND.
  GET DIAGNOSTICS v_linhas = ROW_COUNT;

  PERFORM set_config('gamegb.aplicando_movimento', 'nao', true);

  IF v_linhas = 0 THEN
    RAISE EXCEPTION 'Funcionário do movimento não encontrado.' USING ERRCODE = 'foreign_key_violation';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER movimentospontos_aplica
  AFTER INSERT ON public.movimentospontos
  FOR EACH ROW EXECUTE FUNCTION public.aplica_movimento_no_saldo();

-- ===========================================================================
-- 3. Os dados que ja existem: o livro nasce a partir das entregas aprovadas e
--    estornadas. Se o saldo de alguem nao bater, entra um "Ajuste de abertura"
--    visivel, nunca uma diferenca escondida.
-- ===========================================================================

CREATE TEMP TABLE saldo_anterior AS
  SELECT funcionarioid, contaid, saldopontos AS saldo FROM public.funcionarios;

UPDATE public.funcionarios SET saldopontos = 0, pontostotal = 0
 WHERE saldopontos <> 0 OR coalesce(pontostotal, 0) <> 0;

INSERT INTO public.movimentospontos (contaid, funcionarioid, lojaid, datamovimento, tipo, pontos, descricao, entregaid, criadopor)
SELECT e.contaid, e.funcionarioid, e.lojaid, coalesce(e.dataaprovacao, e.dataenvio), 'aprovacao',
       e.pontosganhos, 'Tarefa aprovada: ' || t.titulo, e.entregaid, e.aprovadopor
  FROM public.entregas e
  JOIN public.tarefas t ON t.tarefaid = e.tarefaid
 WHERE e.statusvalidacao IN ('Aprovada', 'Estornada') AND coalesce(e.pontosganhos, 0) <> 0
 ORDER BY coalesce(e.dataaprovacao, e.dataenvio);

INSERT INTO public.movimentospontos (contaid, funcionarioid, lojaid, datamovimento, tipo, pontos, descricao, entregaid, criadopor)
SELECT e.contaid, e.funcionarioid, e.lojaid, coalesce(e.dataestorno, now()), 'estorno_entrega',
       -e.pontosganhos, 'Estorno: ' || t.titulo, e.entregaid, e.estornadopor
  FROM public.entregas e
  JOIN public.tarefas t ON t.tarefaid = e.tarefaid
 WHERE e.statusvalidacao = 'Estornada' AND coalesce(e.pontosganhos, 0) <> 0
 ORDER BY e.dataestorno;

INSERT INTO public.movimentospontos (contaid, funcionarioid, tipo, pontos, descricao)
SELECT a.contaid, a.funcionarioid, 'ajuste_abertura', a.saldo - f.saldopontos,
       'Ajuste de abertura do extrato (saldo anterior ao livro de movimentos)'
  FROM saldo_anterior a
  JOIN public.funcionarios f ON f.funcionarioid = a.funcionarioid
 WHERE a.saldo <> f.saldopontos;

DROP TABLE saldo_anterior;

-- ===========================================================================
-- 4. Protetor do saldo. Qualquer INSERT ou UPDATE em funcionarios que mexa em
--    saldopontos/pontostotal e recusado, a menos que venha do gatilho acima.
--    Vale para o navegador, para funcoes com poder total, para o servidor e
--    ate para o dono do banco. Regra permanente: ver CLAUDE.md.
-- ===========================================================================

CREATE OR REPLACE FUNCTION public.protege_saldo()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  pelo_livro boolean := current_setting('gamegb.aplicando_movimento', true) = 'sim'
                        AND pg_trigger_depth() >= 2;
BEGIN
  IF pelo_livro THEN
    RETURN NEW;
  END IF;

  IF TG_OP = 'INSERT' AND (coalesce(NEW.saldopontos, 0) <> 0 OR coalesce(NEW.pontostotal, 0) <> 0) THEN
    RAISE EXCEPTION 'Funcionário novo começa com saldo zero. Pontos só entram pelo livro de movimentos.'
      USING ERRCODE = 'restrict_violation';
  END IF;

  IF TG_OP = 'UPDATE' AND (NEW.saldopontos IS DISTINCT FROM OLD.saldopontos
                        OR NEW.pontostotal IS DISTINCT FROM OLD.pontostotal) THEN
    RAISE EXCEPTION 'O saldo só muda gravando um movimento em movimentospontos.'
      USING ERRCODE = 'restrict_violation';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER funcionarios_protege_saldo
  BEFORE INSERT OR UPDATE ON public.funcionarios
  FOR EACH ROW EXECUTE FUNCTION public.protege_saldo();

-- ===========================================================================
-- 5. Aprovar e estornar entrega passam a gravar o movimento em vez de mexer
--    no saldo direto. Comportamento para quem usa: o mesmo.
-- ===========================================================================

CREATE OR REPLACE FUNCTION public.aprovar_entrega(p_entregaid integer)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_conta   integer := public.minha_conta_editavel();
  v_entrega public.entregas%ROWTYPE;
  v_pontos  integer;
  v_titulo  text;
BEGIN
  IF v_conta IS NULL THEN
    RAISE EXCEPTION 'Sua conta não pode alterar dados no momento.' USING ERRCODE = 'insufficient_privilege';
  END IF;

  SELECT * INTO v_entrega FROM public.entregas
   WHERE entregaid = p_entregaid AND contaid = v_conta
     FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Entrega não encontrada.' USING ERRCODE = 'no_data_found';
  END IF;

  IF v_entrega.statusvalidacao <> 'Pendente' THEN
    RAISE EXCEPTION 'Só uma entrega pendente pode ser aprovada. Esta está: %.', v_entrega.statusvalidacao
      USING ERRCODE = 'check_violation';
  END IF;

  SELECT pontos, titulo INTO v_pontos, v_titulo FROM public.tarefas
   WHERE tarefaid = v_entrega.tarefaid AND contaid = v_conta;

  UPDATE public.entregas
     SET statusvalidacao = 'Aprovada', pontosganhos = v_pontos,
         dataaprovacao = now(), aprovadopor = auth.uid()
   WHERE entregaid = p_entregaid;

  IF v_pontos <> 0 THEN
    INSERT INTO public.movimentospontos (contaid, funcionarioid, lojaid, tipo, pontos, descricao, entregaid, criadopor)
    VALUES (v_conta, v_entrega.funcionarioid, v_entrega.lojaid, 'aprovacao', v_pontos,
            'Tarefa aprovada: ' || v_titulo, p_entregaid, auth.uid());
  END IF;

  PERFORM public.apos_aprovar_entrega(p_entregaid);
  RETURN v_pontos;
END;
$$;

CREATE OR REPLACE FUNCTION public.estornar_entrega(p_entregaid integer, p_motivo text)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_conta   integer := public.minha_conta_editavel();
  v_entrega public.entregas%ROWTYPE;
  v_titulo  text;
  v_saldo   integer;
BEGIN
  IF v_conta IS NULL THEN
    RAISE EXCEPTION 'Sua conta não pode alterar dados no momento.' USING ERRCODE = 'insufficient_privilege';
  END IF;

  IF length(btrim(coalesce(p_motivo, ''))) = 0 THEN
    RAISE EXCEPTION 'Informe o motivo do estorno.' USING ERRCODE = 'check_violation';
  END IF;

  SELECT * INTO v_entrega FROM public.entregas
   WHERE entregaid = p_entregaid AND contaid = v_conta
     FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Entrega não encontrada.' USING ERRCODE = 'no_data_found';
  END IF;

  IF v_entrega.statusvalidacao <> 'Aprovada' THEN
    RAISE EXCEPTION 'Só uma entrega aprovada pode ser estornada. Esta está: %.', v_entrega.statusvalidacao
      USING ERRCODE = 'check_violation';
  END IF;

  SELECT titulo INTO v_titulo FROM public.tarefas WHERE tarefaid = v_entrega.tarefaid;

  UPDATE public.entregas
     SET statusvalidacao = 'Estornada', motivoestorno = btrim(p_motivo),
         dataestorno = now(), estornadopor = auth.uid()
   WHERE entregaid = p_entregaid;

  IF coalesce(v_entrega.pontosganhos, 0) <> 0 THEN
    INSERT INTO public.movimentospontos (contaid, funcionarioid, lojaid, tipo, pontos, descricao, entregaid, criadopor)
    VALUES (v_conta, v_entrega.funcionarioid, v_entrega.lojaid, 'estorno_entrega', -v_entrega.pontosganhos,
            'Estorno: ' || v_titulo || ' (' || btrim(p_motivo) || ')', p_entregaid, auth.uid());
  END IF;

  SELECT saldopontos INTO v_saldo FROM public.funcionarios WHERE funcionarioid = v_entrega.funcionarioid;
  RETURN v_saldo;
END;
$$;

