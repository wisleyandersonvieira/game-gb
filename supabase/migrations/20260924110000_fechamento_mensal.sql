-- Etapa 1.11, parte 2: fechamento mensal do ranking.
--
-- Regras (decisões do Wisley, 22/09/2026):
--   * Roda no dia 1, no HORARIO_FECHAMENTO_MENSAL da conta, para o mês anterior.
--   * Dias 1 a 7: provisório, refeito todo dia. Dia 8: definitivo.
--   * "Refazer fechamento" só pelo master, com motivo; a versão anterior fica
--     guardada (situação "substituido").
--   * Grava, por loja ativa e geral da conta: posição, pontos ganhos, pontos
--     regulares, possíveis, confiabilidade, esforço e nota (mesma conta do
--     ranking ao vivo). Cada ponto conta na loja em que a tarefa foi feita.
--   * Sem pontos automáticos para os vencedores.

-- ---------------------------------------------------------------------------
-- 1. Fechamentos (uma versão vale por mês; as anteriores ficam guardadas)
-- ---------------------------------------------------------------------------
CREATE TABLE public.fechamentosmensais (
  fechamentoid  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contaid       integer NOT NULL DEFAULT public.minha_conta() REFERENCES public.contas (contaid) ON DELETE RESTRICT,
  ano           integer NOT NULL,
  mes           integer NOT NULL CHECK (mes BETWEEN 1 AND 12),
  versao        integer NOT NULL DEFAULT 1,
  situacao      varchar(12) NOT NULL CHECK (situacao IN ('provisorio', 'definitivo', 'substituido')),
  origem        varchar(10) NOT NULL CHECK (origem IN ('rotina', 'master')),
  motivo        text,
  fechadopor    uuid,
  fechadoem     timestamptz NOT NULL DEFAULT now(),
  atualizadoem  timestamptz,
  definitivoem  timestamptz,
  substituidoem timestamptz,
  CONSTRAINT fechamentosmensais_conta_unico UNIQUE (contaid, fechamentoid),
  CONSTRAINT fechamentosmensais_versao_unica UNIQUE (contaid, ano, mes, versao),
  CONSTRAINT fechamentosmensais_master_com_motivo CHECK (origem <> 'master' OR length(btrim(coalesce(motivo, ''))) > 0)
);
CREATE UNIQUE INDEX fechamentosmensais_um_valendo
  ON public.fechamentosmensais (contaid, ano, mes) WHERE situacao <> 'substituido';

ALTER TABLE public.fechamentosmensais ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.fechamentosmensais TO authenticated;
GRANT ALL ON public.fechamentosmensais TO service_role;
CREATE POLICY fechamentosmensais_sel ON public.fechamentosmensais FOR SELECT TO authenticated
  USING (contaid = (select public.minha_conta()));

-- ---------------------------------------------------------------------------
-- 2. historicoranking: uma linha por pessoa, por loja (ou geral), por versão
--    (a tabela está vazia: nada a migrar)
-- ---------------------------------------------------------------------------
DROP POLICY IF EXISTS historicoranking_ins ON public.historicoranking;
DROP POLICY IF EXISTS historicoranking_upd ON public.historicoranking;
DROP POLICY IF EXISTS historicoranking_del ON public.historicoranking;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON public.historicoranking FROM anon, authenticated;

DROP INDEX IF EXISTS public.historicoranking_um_por_mes;
ALTER TABLE public.historicoranking ALTER COLUMN lojaid DROP NOT NULL;   -- vazio = geral da conta
ALTER TABLE public.historicoranking ADD COLUMN fechamentoid    integer NOT NULL;
ALTER TABLE public.historicoranking ADD COLUMN pontosregulares integer NOT NULL DEFAULT 0;
ALTER TABLE public.historicoranking ADD COLUMN confiabilidade  numeric(6,2) NOT NULL DEFAULT 0;
ALTER TABLE public.historicoranking ADD COLUMN esforco         numeric(6,2) NOT NULL DEFAULT 0;
ALTER TABLE public.historicoranking ADD COLUMN nota            numeric(6,2) NOT NULL DEFAULT 0;
ALTER TABLE public.historicoranking ADD CONSTRAINT historicoranking_fechamento_fk
  FOREIGN KEY (contaid, fechamentoid) REFERENCES public.fechamentosmensais (contaid, fechamentoid) ON DELETE RESTRICT;
CREATE UNIQUE INDEX historicoranking_uma_linha
  ON public.historicoranking (fechamentoid, coalesce(lojaid, 0), funcionarioid);
CREATE INDEX historicoranking_fechamento_idx ON public.historicoranking (fechamentoid);

-- Linhas de fechamento definitivo ou substituído não mudam nem se apagam.
CREATE OR REPLACE FUNCTION public.protege_historico_ranking()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  v_situacao text;
BEGIN
  SELECT situacao INTO v_situacao FROM public.fechamentosmensais
   WHERE fechamentoid = CASE WHEN TG_OP = 'INSERT' THEN NEW.fechamentoid ELSE OLD.fechamentoid END;
  IF v_situacao IS DISTINCT FROM 'provisorio' AND TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'Fechamento definitivo não muda. Use "Refazer fechamento".' USING ERRCODE = 'restrict_violation';
  END IF;
  IF v_situacao = 'substituido' THEN
    RAISE EXCEPTION 'Fechamento substituído não recebe linhas.' USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;
CREATE TRIGGER historicoranking_protege BEFORE INSERT OR UPDATE OR DELETE ON public.historicoranking
  FOR EACH ROW EXECUTE FUNCTION public.protege_historico_ranking();

-- Versão substituída não volta; definitivo só vira substituído.
CREATE OR REPLACE FUNCTION public.protege_fechamento()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Fechamento não se apaga.' USING ERRCODE = 'restrict_violation';
  END IF;
  IF NEW.contaid <> OLD.contaid OR NEW.ano <> OLD.ano OR NEW.mes <> OLD.mes OR NEW.versao <> OLD.versao THEN
    RAISE EXCEPTION 'Fechamento não muda de mês nem de versão.' USING ERRCODE = 'restrict_violation';
  END IF;
  IF OLD.situacao = 'substituido'
     OR (OLD.situacao = 'definitivo' AND NEW.situacao NOT IN ('definitivo', 'substituido')) THEN
    RAISE EXCEPTION 'Fechamento definitivo não volta a provisório.' USING ERRCODE = 'restrict_violation';
  END IF;
  NEW.atualizadoem := now();
  RETURN NEW;
END;
$$;
CREATE TRIGGER fechamentosmensais_protege BEFORE UPDATE OR DELETE ON public.fechamentosmensais
  FOR EACH ROW EXECUTE FUNCTION public.protege_fechamento();

