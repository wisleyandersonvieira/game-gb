-- Etapa 1.11, parte 1: registro de execuções, lista do dia congelada e
-- "passar tarefa de quem está de folga".
--
-- Regras (decisões do Wisley, 22/09/2026):
--   * As rotinas rodam para todas as contas ativas, cada uma no seu horário
--     (configuracoes), no fuso America/Sao_Paulo. Pulam contas suspensas e
--     lojas desativadas. Uma conta com erro não trava as outras.
--   * Rodar duas vezes nunca duplica. Depois de uma parada, recupera no
--     máximo 7 dias, marcados como "recuperado".
--   * A lista de HOJE é ajustada a cada rodada (acrescenta o que falta,
--     cancela o que deixou de valer), sem mexer em item entregue, justificado
--     ou passado. Os dias passados nunca mudam.
--   * Os pontos de cada item são os do dia em que foi gerado.
--   * As funções da rotina recebem contaid e rodam com poder total (o papel
--     do pg_cron ignora a RLS): por isso filtram a conta em TODA consulta e
--     não são liberadas para ninguém.

-- ---------------------------------------------------------------------------
-- 1. Registro de execuções
-- ---------------------------------------------------------------------------
CREATE TABLE public.rotinasexecucoes (
  execucaoid  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contaid     integer NOT NULL DEFAULT public.minha_conta() REFERENCES public.contas (contaid) ON DELETE RESTRICT,
  rotina      varchar(30) NOT NULL
              CHECK (rotina IN ('lista_do_dia', 'fechamento_mensal', 'conferencia_livro', 'limpeza')),
  referencia  date,
  origem      varchar(10) NOT NULL DEFAULT 'agendada' CHECK (origem IN ('agendada', 'manual')),
  recuperado  boolean NOT NULL DEFAULT false,
  iniciadoem  timestamptz NOT NULL DEFAULT now(),
  terminadoem timestamptz,
  resultado   varchar(10) NOT NULL CHECK (resultado IN ('ok', 'erro')),
  detalhe     jsonb,
  erro        text,
  CONSTRAINT rotinasexecucoes_conta_unico UNIQUE (contaid, execucaoid)
);
CREATE INDEX rotinasexecucoes_conta_idx ON public.rotinasexecucoes (contaid, rotina, iniciadoem DESC);
CREATE INDEX rotinasexecucoes_limpeza_idx ON public.rotinasexecucoes (iniciadoem);

ALTER TABLE public.rotinasexecucoes ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.rotinasexecucoes TO authenticated;
GRANT ALL ON public.rotinasexecucoes TO service_role;
CREATE POLICY rotinasexecucoes_sel ON public.rotinasexecucoes FOR SELECT TO authenticated
  USING (contaid = (select public.minha_conta()));

-- ---------------------------------------------------------------------------
-- 2. Dias com lista gerada (nunca é limpo: diz de onde vêm os números)
-- ---------------------------------------------------------------------------
CREATE TABLE public.diasgerados (
  contaid    integer NOT NULL DEFAULT public.minha_conta() REFERENCES public.contas (contaid) ON DELETE RESTRICT,
  dia        date NOT NULL,
  recuperado boolean NOT NULL DEFAULT false,
  geradoem   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (contaid, dia)
);
ALTER TABLE public.diasgerados ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.diasgerados TO authenticated;
GRANT ALL ON public.diasgerados TO service_role;
CREATE POLICY diasgerados_sel ON public.diasgerados FOR SELECT TO authenticated
  USING (contaid = (select public.minha_conta()));

-- ---------------------------------------------------------------------------
-- 3. Lista do dia (o que cada pessoa devia fazer em cada dia)
-- ---------------------------------------------------------------------------
CREATE TABLE public.tarefasdodia (
  itemid              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contaid             integer NOT NULL DEFAULT public.minha_conta() REFERENCES public.contas (contaid) ON DELETE RESTRICT,
  lojaid              integer NOT NULL,
  dia                 date NOT NULL,
  atribuicaoid        integer NOT NULL,
  funcionarioid       integer NOT NULL,
  tarefaid            integer NOT NULL,
  tipofrequencia      varchar(20) NOT NULL,
  pontos              integer NOT NULL,
  situacao            varchar(12) NOT NULL CHECK (situacao IN ('devida', 'folga', 'afastamento', 'cancelada')),
  passadapara         integer,
  passadaatribuicaoid integer,
  passadaem           timestamptz,
  passadapor          uuid,
  recuperado          boolean NOT NULL DEFAULT false,
  geradoem            timestamptz NOT NULL DEFAULT now(),
  atualizadoem        timestamptz,
  CONSTRAINT tarefasdodia_um_por_dia UNIQUE (contaid, dia, atribuicaoid),
  CONSTRAINT tarefasdodia_conta_unico UNIQUE (contaid, itemid),
  CONSTRAINT tarefasdodia_loja_fk FOREIGN KEY (contaid, lojaid) REFERENCES public.lojas (contaid, lojaid) ON DELETE RESTRICT,
  CONSTRAINT tarefasdodia_atribuicao_fk FOREIGN KEY (contaid, atribuicaoid)
    REFERENCES public.tarefasatribuidas (contaid, atribuicaoid) ON DELETE RESTRICT,
  CONSTRAINT tarefasdodia_funcionario_fk FOREIGN KEY (contaid, funcionarioid)
    REFERENCES public.funcionarios (contaid, funcionarioid) ON DELETE RESTRICT,
  CONSTRAINT tarefasdodia_tarefa_fk FOREIGN KEY (contaid, tarefaid) REFERENCES public.tarefas (contaid, tarefaid) ON DELETE RESTRICT,
  CONSTRAINT tarefasdodia_passadapara_fk FOREIGN KEY (contaid, passadapara)
    REFERENCES public.funcionarios (contaid, funcionarioid) ON DELETE RESTRICT,
  CONSTRAINT tarefasdodia_passadaatribuicao_fk FOREIGN KEY (contaid, passadaatribuicaoid)
    REFERENCES public.tarefasatribuidas (contaid, atribuicaoid) ON DELETE RESTRICT,
  -- Só se passa tarefa de quem está de folga ou afastado.
  CONSTRAINT tarefasdodia_passada_so_de_folga CHECK (passadapara IS NULL OR situacao IN ('folga', 'afastamento'))
);
CREATE INDEX tarefasdodia_dia_idx ON public.tarefasdodia (contaid, dia);
CREATE INDEX tarefasdodia_pessoa_idx ON public.tarefasdodia (funcionarioid, dia);
CREATE INDEX tarefasdodia_atribuicao_idx ON public.tarefasdodia (atribuicaoid, dia);

ALTER TABLE public.tarefasdodia ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.tarefasdodia TO authenticated;
GRANT ALL ON public.tarefasdodia TO service_role;
CREATE POLICY tarefasdodia_sel ON public.tarefasdodia FOR SELECT TO authenticated
  USING (contaid = (select public.minha_conta()));

-- Dia que já passou não muda, por nenhum caminho.
CREATE OR REPLACE FUNCTION public.protege_lista_do_dia()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  IF OLD.dia < public.dia_em_sao_paulo(now()) THEN
    RAISE EXCEPTION 'A lista de um dia que já passou não muda.' USING ERRCODE = 'restrict_violation';
  END IF;
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Item da lista do dia não se apaga: é cancelado.' USING ERRCODE = 'restrict_violation';
  END IF;
  IF NEW.contaid <> OLD.contaid OR NEW.dia <> OLD.dia OR NEW.atribuicaoid <> OLD.atribuicaoid
     OR NEW.funcionarioid <> OLD.funcionarioid OR NEW.pontos <> OLD.pontos OR NEW.lojaid <> OLD.lojaid THEN
    RAISE EXCEPTION 'Só a situação e o repasse de um item mudam.' USING ERRCODE = 'restrict_violation';
  END IF;
  IF OLD.passadapara IS NOT NULL AND (NEW.passadapara IS DISTINCT FROM OLD.passadapara OR NEW.situacao <> OLD.situacao) THEN
    RAISE EXCEPTION 'Tarefa já passada para outra pessoa não muda mais.' USING ERRCODE = 'restrict_violation';
  END IF;
  NEW.atualizadoem := now();
  RETURN NEW;
END;
$$;
CREATE TRIGGER tarefasdodia_protege BEFORE UPDATE OR DELETE ON public.tarefasdodia
  FOR EACH ROW EXECUTE FUNCTION public.protege_lista_do_dia();

-- Tarefa passada nasce como única de hoje, com origematribuicaoid apontando
-- para a original. Uma vez por dia, no máximo.
CREATE UNIQUE INDEX tarefasatribuidas_passada_uma_vez
  ON public.tarefasatribuidas (contaid, origematribuicaoid, public.dia_em_sao_paulo(dataagendamento))
