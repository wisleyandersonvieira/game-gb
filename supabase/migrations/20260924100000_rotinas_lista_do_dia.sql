-- Tarefas de hoje de quem está de folga ou afastado, numa loja.
CREATE OR REPLACE FUNCTION public.tarefas_de_folga_hoje(p_lojaid integer)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
  WITH hoje AS (SELECT public.dia_em_sao_paulo(now()) AS dia),
  itens AS (
    SELECT c.atribuicaoid, c.funcionarioid, c.tarefaid, c.tipofrequencia, c.pontos, c.situacao, i.passadapara
      FROM hoje CROSS JOIN LATERAL public.lista_candidatos(public.minha_conta(), hoje.dia) c
      LEFT JOIN public.tarefasdodia i ON i.atribuicaoid = c.atribuicaoid AND i.dia = hoje.dia
     WHERE c.lojaid = p_lojaid AND c.situacao IN ('folga', 'afastamento')
  )
  SELECT coalesce(jsonb_agg(jsonb_build_object(
           'atribuicaoid', it.atribuicaoid,
           'titulo',       t.titulo,
           'pontos',       it.pontos,
           'pessoa',       f.nomecompleto,
           'motivo',       it.situacao,
           'passadapara',  p.nomecompleto,
           'entregue',     EXISTS (SELECT 1 FROM public.entregas e, hoje
                                    WHERE e.atribuicaoid = it.atribuicaoid
                                      AND e.statusvalidacao IN ('Pendente', 'Aprovada')
                                      AND (it.tipofrequencia = 'Unica' OR public.dia_em_sao_paulo(e.dataenvio) = hoje.dia)))
           ORDER BY f.nomecompleto, t.titulo), '[]'::jsonb)
    FROM itens it
    JOIN public.tarefas t      ON t.tarefaid = it.tarefaid
    JOIN public.funcionarios f ON f.funcionarioid = it.funcionarioid
    LEFT JOIN public.funcionarios p ON p.funcionarioid = it.passadapara
$$;

-- Quem trabalha hoje na loja (pode receber uma tarefa de quem está de folga).
CREATE OR REPLACE FUNCTION public.quem_trabalha_hoje(p_lojaid integer)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
  SELECT coalesce(jsonb_agg(jsonb_build_object('funcionarioid', f.funcionarioid, 'nome', f.nomecompleto)
                            ORDER BY f.nomecompleto), '[]'::jsonb)
    FROM public.funcionarios f
    JOIN public.funcionarioslojas fl ON fl.funcionarioid = f.funcionarioid AND fl.lojaid = p_lojaid AND fl.ativo
   WHERE f.ativo
     AND public.dia_de_trabalho(f.diadefolga, f.domingofolgamensal, f.datainicioafastamento,
                                f.datafimafastamento, public.dia_em_sao_paulo(now()))
$$;

-- Passa a tarefa de hoje de quem está de folga para quem trabalha hoje.
-- Vira uma tarefa única de hoje, com os mesmos pontos (a tarefa é a mesma).
-- Para quem recebe é esforço extra: não entra nos pontos possíveis.
CREATE OR REPLACE FUNCTION public.passar_tarefa_de_folga(p_atribuicaoid integer, p_funcionarioid integer)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_conta integer := public.minha_conta_editavel();
  v_hoje  date    := public.dia_em_sao_paulo(now());
  v_item  public.tarefasdodia%ROWTYPE;
  v_nome  text;
  v_nova  integer;
BEGIN
  IF v_conta IS NULL THEN
    RAISE EXCEPTION 'Sua conta não pode alterar dados no momento.' USING ERRCODE = 'insufficient_privilege';
  END IF;

  -- Garante a lista de hoje (se a rotina ainda não rodou).
  PERFORM public.lista_do_dia_gerar(v_conta, v_hoje, v_hoje, false);

  SELECT * INTO v_item FROM public.tarefasdodia
   WHERE contaid = v_conta AND dia = v_hoje AND atribuicaoid = p_atribuicaoid
   FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Esta tarefa não está na lista de hoje.' USING ERRCODE = 'no_data_found';
  END IF;
  IF v_item.situacao NOT IN ('folga', 'afastamento') THEN
    RAISE EXCEPTION 'Só se passa tarefa de quem está de folga ou afastado hoje.' USING ERRCODE = 'check_violation';
  END IF;
  IF v_item.passadapara IS NOT NULL THEN
    SELECT nomecompleto INTO v_nome FROM public.funcionarios WHERE funcionarioid = v_item.passadapara;
    RAISE EXCEPTION 'Esta tarefa já foi passada hoje para %.', v_nome USING ERRCODE = 'unique_violation';
  END IF;
  IF public.item_tratado(v_item.atribuicaoid, v_item.tipofrequencia, v_hoje, NULL) THEN
    RAISE EXCEPTION 'Esta tarefa já foi entregue ou justificada hoje.' USING ERRCODE = 'check_violation';
  END IF;
  IF p_funcionarioid = v_item.funcionarioid OR NOT EXISTS (
       SELECT 1 FROM public.funcionarios f
         JOIN public.funcionarioslojas fl ON fl.funcionarioid = f.funcionarioid AND fl.lojaid = v_item.lojaid
                                         AND fl.ativo AND fl.contaid = v_conta
        WHERE f.funcionarioid = p_funcionarioid AND f.contaid = v_conta AND f.ativo
          AND public.dia_de_trabalho(f.diadefolga, f.domingofolgamensal, f.datainicioafastamento,
                                     f.datafimafastamento, v_hoje)) THEN
    RAISE EXCEPTION 'Escolha alguém ativo, da mesma loja, que trabalha hoje.' USING ERRCODE = 'check_violation';
  END IF;

  INSERT INTO public.tarefasatribuidas (contaid, tarefaid, funcionarioid, lojaid, tipofrequencia,
                                        dataatribuicao, dataagendamento, origematribuicaoid)
  VALUES (v_conta, v_item.tarefaid, p_funcionarioid, v_item.lojaid, 'Unica', now(), now(), v_item.atribuicaoid)
  RETURNING atribuicaoid INTO v_nova;

  UPDATE public.tarefasdodia
     SET passadapara = p_funcionarioid, passadaatribuicaoid = v_nova, passadaem = now(), passadapor = auth.uid()
   WHERE itemid = v_item.itemid;

  RETURN v_nova;
END;
$$;

-- A original, depois de passada, não recebe entrega hoje.
CREATE OR REPLACE FUNCTION public.entrega_nao_passada()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF NEW.atribuicaoid IS NOT NULL
     AND public.passada_hoje(NEW.atribuicaoid, public.dia_em_sao_paulo(coalesce(NEW.dataenvio, now()))) THEN
    RAISE EXCEPTION 'Esta tarefa foi passada para outra pessoa hoje.' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER entregas_nao_passada BEFORE INSERT ON public.entregas
  FOR EACH ROW EXECUTE FUNCTION public.entrega_nao_passada();

-- ---------------------------------------------------------------------------
-- 7. Nota do mês, pendências e justificativas: dias gerados vêm da lista
--    congelada; dias sem lista (antes da primeira geração ou numa parada
--    maior que 7 dias) continuam pela regra do cadastro.
--    Tarefa recebida de quem estava de folga (origematribuicaoid) é esforço
--    extra: conta nos pontos ganhos, não nos possíveis nem na confiabilidade.
-- ---------------------------------------------------------------------------

-- Versão por conta, usada pela tela (com a conta de quem está logado) e pelo
-- fechamento mensal. Filtra a conta em todas as tabelas.
CREATE OR REPLACE FUNCTION public.ranking_mensal_da_conta(
  p_contaid integer, p_ano integer, p_mes integer, p_lojaid integer, p_fim date
)
RETURNS TABLE (
  funcionarioid   integer,
  nomecompleto    varchar,
  pontosganhos    integer,
  pontosregulares integer,
  pontospossiveis integer,
  confiabilidade  numeric,
  esforco         numeric,
  nota            numeric
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
  WITH janela AS (
    SELECT make_date(p_ano, p_mes, 1) AS ini,
           least((make_date(p_ano, p_mes, 1) + interval '1 month - 1 day')::date, p_fim) AS fim
  ),
  gerados AS (
    SELECT dg.dia FROM public.diasgerados dg, janela j
     WHERE dg.contaid = p_contaid AND dg.dia BETWEEN j.ini AND j.fim
  ),
  lista AS (
    SELECT i.funcionarioid AS fid, sum(i.pontos)::integer AS pts
      FROM public.tarefasdodia i
      JOIN gerados g ON g.dia = i.dia
     WHERE i.contaid = p_contaid
       AND i.situacao = 'devida'
       AND (p_lojaid IS NULL OR i.lojaid = p_lojaid)
       AND NOT public.tem_justificativa(i.atribuicaoid, i.tipofrequencia, i.dia, true)
     GROUP BY i.funcionarioid
  ),
  recorrentes AS (
    SELECT ta.funcionarioid AS fid, sum(t.pontos)::integer AS pts
      FROM public.tarefasatribuidas ta
      JOIN public.tarefas t      ON t.tarefaid = ta.tarefaid AND t.contaid = p_contaid
      JOIN public.funcionarios f ON f.funcionarioid = ta.funcionarioid AND f.contaid = p_contaid
      CROSS JOIN janela j
      CROSS JOIN LATERAL generate_series(
        greatest(j.ini,
                 coalesce(public.dia_em_sao_paulo(ta.dataatribuicao), j.ini),
                 coalesce(ta.datainiciovigencia, j.ini)),
        least(j.fim, coalesce(ta.datafimvigencia - 1, j.fim)),
        interval '1 day') AS g(d)
     WHERE ta.contaid = p_contaid
       AND ta.funcionarioid IS NOT NULL
       AND ta.origematribuicaoid IS NULL
       AND ta.tipofrequencia IN ('Diaria', 'Semanal', 'Mensal')
       AND (p_lojaid IS NULL OR ta.lojaid = p_lojaid)
       AND g.d::date NOT IN (SELECT dia FROM gerados)
       AND public.tarefa_cai_no_dia(ta.tipofrequencia, ta.valorfrequencia, ta.dataagendamento, g.d::date)
       AND public.dia_de_trabalho(f.diadefolga, f.domingofolgamensal,
                                  f.datainicioafastamento, f.datafimafastamento, g.d::date)
       AND NOT public.tem_justificativa(ta.atribuicaoid, ta.tipofrequencia, g.d::date, true)
     GROUP BY ta.funcionarioid
  ),
  unicas AS (
    SELECT ta.funcionarioid AS fid, sum(t.pontos)::integer AS pts
      FROM public.tarefasatribuidas ta
      JOIN public.tarefas t ON t.tarefaid = ta.tarefaid AND t.contaid = p_contaid
      CROSS JOIN janela j
     WHERE ta.contaid = p_contaid
       AND ta.funcionarioid IS NOT NULL
       AND ta.origematribuicaoid IS NULL
       AND ta.tipofrequencia = 'Unica'
       AND (p_lojaid IS NULL OR ta.lojaid = p_lojaid)
       AND public.dia_em_sao_paulo(coalesce(ta.dataagendamento, ta.dataatribuicao)) BETWEEN j.ini AND j.fim
       AND public.dia_em_sao_paulo(coalesce(ta.dataagendamento, ta.dataatribuicao)) NOT IN (SELECT dia FROM gerados)
       AND (ta.datafimvigencia IS NULL
            OR ta.datafimvigencia > public.dia_em_sao_paulo(coalesce(ta.dataagendamento, ta.dataatribuicao)))
       AND NOT public.tem_justificativa(ta.atribuicaoid, 'Unica', NULL, true)
     GROUP BY ta.funcionarioid
  ),
  regulares AS (
    SELECT e.funcionarioid AS fid, sum(e.pontosganhos)::integer AS pts
      FROM public.entregas e
      JOIN public.tarefasatribuidas ta ON ta.atribuicaoid = e.atribuicaoid AND ta.contaid = p_contaid
      CROSS JOIN janela j
     WHERE e.contaid = p_contaid
       AND e.statusvalidacao = 'Aprovada'
       AND ta.origematribuicaoid IS NULL
       AND (p_lojaid IS NULL OR e.lojaid = p_lojaid)
       AND public.dia_em_sao_paulo(e.dataenvio) BETWEEN j.ini AND j.fim
     GROUP BY e.funcionarioid
  ),
  ganhos AS (
    SELECT e.funcionarioid AS fid, sum(e.pontosganhos)::integer AS pts
      FROM public.entregas e
      CROSS JOIN janela j
     WHERE e.contaid = p_contaid
       AND e.statusvalidacao = 'Aprovada'
       AND (p_lojaid IS NULL OR e.lojaid = p_lojaid)
       AND public.dia_em_sao_paulo(e.dataaprovacao) BETWEEN j.ini AND j.fim
     GROUP BY e.funcionarioid
  ),
  pessoas AS (
    SELECT fid FROM lista UNION SELECT fid FROM recorrentes UNION SELECT fid FROM unicas
    UNION SELECT fid FROM regulares UNION SELECT fid FROM ganhos
  ),
  base AS (
    SELECT p.fid,
           f.nomecompleto AS nome,
           coalesce(g.pts, 0)                                        AS ganhos,
           coalesce(r.pts, 0)                                        AS regulares,
           coalesce(li.pts, 0) + coalesce(rc.pts, 0) + coalesce(u.pts, 0) AS possiveis
      FROM pessoas p
      JOIN public.funcionarios f ON f.funcionarioid = p.fid AND f.contaid = p_contaid
      LEFT JOIN ganhos g       ON g.fid = p.fid
      LEFT JOIN regulares r    ON r.fid = p.fid
      LEFT JOIN lista li       ON li.fid = p.fid
      LEFT JOIN recorrentes rc ON rc.fid = p.fid
      LEFT JOIN unicas u       ON u.fid = p.fid
  ),
  calc AS (
    SELECT b.*,
           CASE WHEN b.possiveis > 0 THEN least(100, round(b.regulares * 100.0 / b.possiveis, 2)) ELSE 0 END AS conf,
           CASE WHEN max(b.ganhos) OVER () > 0 THEN round(b.ganhos * 100.0 / max(b.ganhos) OVER (), 2) ELSE 0 END AS esf
      FROM base b
  )
  SELECT c.fid, c.nome, c.ganhos, c.regulares, c.possiveis, c.conf, c.esf,
         round(c.conf * 0.5 + c.esf * 0.5, 2)
    FROM calc c
   ORDER BY 8 DESC, 3 DESC, 2
$$;

