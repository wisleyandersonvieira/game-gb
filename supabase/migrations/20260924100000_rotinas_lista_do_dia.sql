-- Dia e hora locais de um instante. Com horário de verão, uma hora que "não
-- existe" (relógio pula) conta como passada assim que o relógio a ultrapassa;
-- a hora repetida não duplica nada porque as rotinas não repetem o que já fizeram.
CREATE OR REPLACE FUNCTION public.rotina_hora_local(p_agora timestamptz, p_fuso text DEFAULT 'America/Sao_Paulo')
RETURNS TABLE (dia date, hora time)
LANGUAGE sql
STABLE
SET search_path = public, pg_temp
AS $$
  SELECT (p_agora AT TIME ZONE p_fuso)::date, (p_agora AT TIME ZONE p_fuso)::time
$$;

-- Horário configurado da conta (ou o padrão).
CREATE OR REPLACE FUNCTION public.rotina_horario(p_contaid integer, p_chave text, p_padrao time)
RETURNS time
LANGUAGE sql
STABLE
SET search_path = public, pg_temp
AS $$
  SELECT coalesce((SELECT nullif(btrim(valor), '')::time FROM public.configuracoes
                    WHERE contaid = p_contaid AND chave = p_chave), p_padrao)
$$;

-- Grava uma execução. O mesmo erro repetido só é gravado uma vez por hora.
CREATE OR REPLACE FUNCTION public.rotina_registrar(
  p_contaid    integer,
  p_rotina     text,
  p_referencia date,
  p_origem     text,
  p_inicio     timestamptz,
  p_resultado  text,
  p_detalhe    jsonb,
  p_erro       text,
  p_recuperado boolean DEFAULT false
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF p_resultado = 'erro' AND EXISTS (
       SELECT 1 FROM public.rotinasexecucoes
        WHERE contaid = p_contaid AND rotina = p_rotina AND resultado = 'erro'
          AND referencia IS NOT DISTINCT FROM p_referencia
          AND erro IS NOT DISTINCT FROM p_erro
          AND iniciadoem > clock_timestamp() - interval '1 hour') THEN
    RETURN;
  END IF;
  INSERT INTO public.rotinasexecucoes (contaid, rotina, referencia, origem, recuperado, iniciadoem, terminadoem,
                                       resultado, detalhe, erro)
  VALUES (p_contaid, p_rotina, p_referencia, p_origem, coalesce(p_recuperado, false), p_inicio, clock_timestamp(),
          p_resultado, p_detalhe, left(p_erro, 500));
END;
$$;

-- Atribuições que valem num dia, com a situação da pessoa nesse dia.
-- Filtra a conta em todas as tabelas (roda também com poder total).
CREATE OR REPLACE FUNCTION public.lista_candidatos(p_contaid integer, p_dia date)
RETURNS TABLE (
  atribuicaoid   integer,
  lojaid         integer,
  funcionarioid  integer,
  tarefaid       integer,
  tipofrequencia varchar,
  pontos         integer,
  situacao       text
)
LANGUAGE sql
STABLE
SET search_path = public, pg_temp
AS $$
  SELECT ta.atribuicaoid, ta.lojaid, ta.funcionarioid, ta.tarefaid, ta.tipofrequencia, t.pontos,
         CASE
           WHEN f.datainicioafastamento IS NOT NULL AND f.datafimafastamento IS NOT NULL
                AND p_dia BETWEEN f.datainicioafastamento AND f.datafimafastamento THEN 'afastamento'
           WHEN NOT public.dia_de_trabalho(f.diadefolga, f.domingofolgamensal, NULL, NULL, p_dia) THEN 'folga'
           ELSE 'devida'
         END
    FROM public.tarefasatribuidas ta
    JOIN public.tarefas t            ON t.tarefaid = ta.tarefaid AND t.contaid = p_contaid
    JOIN public.funcionarios f       ON f.funcionarioid = ta.funcionarioid AND f.contaid = p_contaid
    JOIN public.funcionarioslojas fl ON fl.funcionarioid = ta.funcionarioid AND fl.lojaid = ta.lojaid
                                    AND fl.contaid = p_contaid
    JOIN public.lojas l              ON l.lojaid = ta.lojaid AND l.contaid = p_contaid
   WHERE ta.contaid = p_contaid
     AND ta.funcionarioid IS NOT NULL
     AND ta.origematribuicaoid IS NULL          -- tarefa recebida de quem está de folga é extra
     AND f.ativo AND fl.ativo AND l.ativa AND coalesce(t.ativa, true)
     AND (
       (ta.tipofrequencia IN ('Diaria', 'Semanal', 'Mensal')
        AND public.tarefa_cai_no_dia(ta.tipofrequencia, ta.valorfrequencia, ta.dataagendamento, p_dia)
        AND p_dia >= coalesce(public.dia_em_sao_paulo(ta.dataatribuicao), p_dia)
        AND p_dia >= coalesce(ta.datainiciovigencia, p_dia)
        AND (ta.datafimvigencia IS NULL OR p_dia < ta.datafimvigencia))
       OR
       (ta.tipofrequencia = 'Unica'
        AND public.dia_em_sao_paulo(coalesce(ta.dataagendamento, ta.dataatribuicao)) = p_dia
        AND (ta.datafimvigencia IS NULL OR ta.datafimvigencia > p_dia))
     )
$$;

-- O item já foi "tratado" (entregue, justificado ou passado)? Então a
-- reconciliação não mexe nele.
CREATE OR REPLACE FUNCTION public.item_tratado(p_atribuicaoid integer, p_tipo varchar, p_dia date, p_passadapara integer)
RETURNS boolean
LANGUAGE sql
STABLE
SET search_path = public, pg_temp
AS $$
  SELECT p_passadapara IS NOT NULL
      OR EXISTS (SELECT 1 FROM public.entregas e
                  WHERE e.atribuicaoid = p_atribuicaoid
                    AND e.statusvalidacao IN ('Pendente', 'Aprovada')
                    AND (p_tipo = 'Unica' OR public.dia_em_sao_paulo(e.dataenvio) = p_dia))
      OR public.tem_justificativa(p_atribuicaoid, p_tipo, p_dia, false)
$$;

-- Gera (ou ajusta) a lista de um dia de uma conta.
--   p_dia < p_hoje: só acrescenta o que falta (dia recuperado); não muda nada.
--   p_dia = p_hoje: acrescenta o que falta, cancela o que deixou de valer e
--                   atualiza folga/afastamento; nunca mexe em item tratado.
CREATE OR REPLACE FUNCTION public.lista_do_dia_gerar(p_contaid integer, p_dia date, p_hoje date, p_recuperado boolean)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_novos      integer := 0;
  v_cancelados integer := 0;
  v_ajustados  integer := 0;
BEGIN
  IF p_dia > p_hoje THEN
    RAISE EXCEPTION 'Não se gera lista de um dia que ainda não chegou.' USING ERRCODE = 'check_violation';
  END IF;
  -- Uma geração por conta de cada vez (duas rodadas simultâneas esperam).
  PERFORM pg_advisory_xact_lock(7311, p_contaid);

  INSERT INTO public.tarefasdodia (contaid, lojaid, dia, atribuicaoid, funcionarioid, tarefaid,
                                   tipofrequencia, pontos, situacao, recuperado)
  SELECT p_contaid, c.lojaid, p_dia, c.atribuicaoid, c.funcionarioid, c.tarefaid,
         c.tipofrequencia, c.pontos, c.situacao, p_recuperado
    FROM public.lista_candidatos(p_contaid, p_dia) c
  ON CONFLICT (contaid, dia, atribuicaoid) DO NOTHING;
  GET DIAGNOSTICS v_novos = ROW_COUNT;

  IF p_dia = p_hoje THEN
    UPDATE public.tarefasdodia i
       SET situacao = 'cancelada'
     WHERE i.contaid = p_contaid AND i.dia = p_dia AND i.situacao <> 'cancelada'
       AND NOT EXISTS (SELECT 1 FROM public.lista_candidatos(p_contaid, p_dia) c WHERE c.atribuicaoid = i.atribuicaoid)
       AND NOT public.item_tratado(i.atribuicaoid, i.tipofrequencia, i.dia, i.passadapara);
    GET DIAGNOSTICS v_cancelados = ROW_COUNT;

    UPDATE public.tarefasdodia i
       SET situacao = c.situacao
      FROM public.lista_candidatos(p_contaid, p_dia) c
     WHERE i.contaid = p_contaid AND i.dia = p_dia AND i.atribuicaoid = c.atribuicaoid
       AND i.situacao IS DISTINCT FROM c.situacao
       AND NOT public.item_tratado(i.atribuicaoid, i.tipofrequencia, i.dia, i.passadapara);
    GET DIAGNOSTICS v_ajustados = ROW_COUNT;
  END IF;

  INSERT INTO public.diasgerados (contaid, dia, recuperado)
  VALUES (p_contaid, p_dia, p_recuperado)
  ON CONFLICT (contaid, dia) DO NOTHING;

  RETURN jsonb_build_object(
    'dia', p_dia, 'novos', v_novos, 'cancelados', v_cancelados, 'ajustados', v_ajustados,
    'devidas',  (SELECT count(*) FROM public.tarefasdodia WHERE contaid = p_contaid AND dia = p_dia AND situacao = 'devida'),
    'folgas',   (SELECT count(*) FROM public.tarefasdodia WHERE contaid = p_contaid AND dia = p_dia
                   AND situacao IN ('folga', 'afastamento')),
    'canceladas', (SELECT count(*) FROM public.tarefasdodia WHERE contaid = p_contaid AND dia = p_dia AND situacao = 'cancelada'));
END;
$$;

-- A rotina da lista para uma conta: recupera dias perdidos (até 7) e gera ou
-- ajusta o dia de hoje (a partir do horário da conta).
CREATE OR REPLACE FUNCTION public.rotina_lista_do_dia(p_contaid integer, p_agora timestamptz, p_origem text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_hoje     date;
  v_hora     time;
  v_primeiro date;
  v_ja       boolean;
  v_inicio   timestamptz;
  v_res      jsonb;
  v_hoje_res jsonb;
  v_recup    integer := 0;
  d          date;
BEGIN
  SELECT x.dia, x.hora INTO v_hoje, v_hora FROM public.rotina_hora_local(p_agora) x;

  -- Dias perdidos: só depois da primeira geração da conta, no máximo 7 para trás.
  SELECT min(dia) INTO v_primeiro FROM public.diasgerados WHERE contaid = p_contaid;
  IF v_primeiro IS NOT NULL THEN
    FOR d IN
      SELECT g::date FROM generate_series(greatest(v_primeiro, v_hoje - 7), v_hoje - 1, interval '1 day') g
       WHERE NOT EXISTS (SELECT 1 FROM public.diasgerados dg WHERE dg.contaid = p_contaid AND dg.dia = g::date)
       ORDER BY 1
    LOOP
      v_inicio := clock_timestamp();
      BEGIN
        v_res := public.lista_do_dia_gerar(p_contaid, d, v_hoje, true);
        PERFORM public.rotina_registrar(p_contaid, 'lista_do_dia', d, p_origem, v_inicio, 'ok', v_res, NULL, true);
        v_recup := v_recup + 1;
      EXCEPTION WHEN OTHERS THEN
        PERFORM public.rotina_registrar(p_contaid, 'lista_do_dia', d, p_origem, v_inicio, 'erro', NULL, SQLERRM, true);
      END;
    END LOOP;
  END IF;

  -- Hoje.
  v_inicio := clock_timestamp();
  BEGIN
    v_ja := EXISTS (SELECT 1 FROM public.diasgerados WHERE contaid = p_contaid AND dia = v_hoje);
    IF p_origem = 'manual' OR v_ja
       OR v_hora >= public.rotina_horario(p_contaid, 'HORARIO_GERACAO_TAREFAS', '00:05') THEN
      v_hoje_res := public.lista_do_dia_gerar(p_contaid, v_hoje, v_hoje, false);
      -- Registra a primeira geração do dia, a rodada manual e qualquer ajuste.
      IF NOT v_ja OR p_origem = 'manual'
         OR (v_hoje_res->>'novos')::integer + (v_hoje_res->>'cancelados')::integer
            + (v_hoje_res->>'ajustados')::integer > 0 THEN
        PERFORM public.rotina_registrar(p_contaid, 'lista_do_dia', v_hoje, p_origem, v_inicio, 'ok',
                                        v_hoje_res || jsonb_build_object('ajuste', v_ja), NULL, false);
      END IF;
    END IF;
  EXCEPTION WHEN OTHERS THEN
    PERFORM public.rotina_registrar(p_contaid, 'lista_do_dia', v_hoje, p_origem, v_inicio, 'erro', NULL, SQLERRM, false);
    v_hoje_res := jsonb_build_object('erro', SQLERRM);
  END;

  RETURN jsonb_build_object('recuperados', v_recup, 'hoje', v_hoje_res);
END;
$$;

