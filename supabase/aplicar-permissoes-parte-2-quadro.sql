-- ---------------------------------------------------------------------------
-- 2. O login que já fez alguma coisa não se apaga (só se bloqueia)
-- ---------------------------------------------------------------------------
-- "Fez alguma coisa" = aparece em qualquer coluna "quem fez" (as que apontam
-- para o login e ficariam vazias com o apagamento) ou no histórico de
-- permissões. A lista de colunas vem do próprio banco: coluna nova do mesmo
-- tipo entra sozinha. Um login recém-criado, sem nada feito, ainda se apaga
-- (é o que o servidor faz quando a criação falha no meio).
CREATE OR REPLACE FUNCTION public.protege_login_com_atos()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE r record; v boolean; onde text := '';
BEGIN
  FOR r IN SELECT c.conrelid::regclass AS tabela, a.attname AS coluna
             FROM pg_constraint c JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
            WHERE c.contype = 'f' AND c.confrelid = 'auth.users'::regclass AND c.confdeltype <> 'c' LOOP
    EXECUTE format('SELECT EXISTS (SELECT 1 FROM %s WHERE %I = $1)', r.tabela, r.coluna) INTO v USING OLD.id;
    IF v THEN onde := onde || r.tabela || '.' || r.coluna || ' '; END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM public.permissoeshistorico WHERE quem = OLD.id) THEN
    onde := onde || 'permissoeshistorico.quem ';
  END IF;
  IF onde <> '' THEN
    RAISE EXCEPTION 'Este login já registrou ações no sistema (%): não pode ser apagado. Bloqueie o acesso em vez de apagar.', btrim(onde)
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN OLD;
END;
$$;
REVOKE ALL ON FUNCTION public.protege_login_com_atos() FROM public, anon, authenticated;
DROP TRIGGER IF EXISTS stgame_login_com_atos ON auth.users;
CREATE TRIGGER stgame_login_com_atos
  BEFORE DELETE ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.protege_login_com_atos();

