-- ---------------------------------------------------------------------------
-- 1. Autores: o nome de cada login em cada momento
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.autores (
  autorid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contaid integer NOT NULL REFERENCES public.contas (contaid) ON DELETE RESTRICT,
  userid  uuid NOT NULL,
  nome    text NOT NULL,
  email   text,
  -- O relógio de verdade, não a hora do começo da transação: um ato e uma
  -- troca de nome na MESMA transação ficam em ordem.
  desde   timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS autores_login_idx ON public.autores (userid, desde DESC);
ALTER TABLE public.autores ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.autores FROM anon, authenticated;
GRANT SELECT ON public.autores TO authenticated;
GRANT ALL ON public.autores TO service_role;
DROP POLICY IF EXISTS autores_sel ON public.autores;
CREATE POLICY autores_sel ON public.autores FOR SELECT TO authenticated
  USING (contaid = (select public.minha_conta()) AND (select public.sou_master()));
COMMENT ON TABLE public.autores IS
  'O nome (e o e-mail) de cada login em cada momento, para "quem fez" nunca depender do login continuar existindo. Só recebe linha nova; na exclusão de dados (LGPD) o nome vira "pessoa removida".';

-- O nome que o login tem AGORA: a pessoa (colaborador, nome dado pelo
-- master), a loja (tablet) ou o E-MAIL do gestor. Nunca o nome de exibição
-- (user_metadata): o próprio usuário edita, e um "quem fez" que a pessoa
-- escolhe não é auditoria (e a seção 14 do teste proíbe ler). Interna.
CREATE OR REPLACE FUNCTION public.nome_do_login_agora(p_userid uuid)
RETURNS TABLE (contaid integer, nome text, email text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT cu.contaid,
         CASE cu.papel
           WHEN 'colaborador' THEN (SELECT f.nomecompleto FROM public.funcionarios f
                                     WHERE f.contaid = cu.contaid AND f.funcionarioid = cu.funcionarioid)
           WHEN 'loja' THEN 'Tablet da ' || (SELECT l.nome FROM public.lojas l
                                              WHERE l.contaid = cu.contaid AND l.lojaid = cu.lojaid)
           ELSE au.email
         END,
         au.email::text
    FROM public.contasusuarios cu
    LEFT JOIN auth.users au ON au.id = cu.userid
   WHERE cu.userid = p_userid
$$;
REVOKE ALL ON FUNCTION public.nome_do_login_agora(uuid) FROM public, anon, authenticated;

-- Grava uma linha nova só se o nome ou o e-mail mudou. Interna.
CREATE OR REPLACE FUNCTION public.registrar_autor(p_userid uuid)
RETURNS void
LANGUAGE sql
VOLATILE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  INSERT INTO public.autores (contaid, userid, nome, email)
  SELECT n.contaid, p_userid, coalesce(n.nome, n.email, 'sem nome'), n.email
    FROM public.nome_do_login_agora(p_userid) n
   WHERE n.contaid IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM (SELECT a.nome, a.email FROM public.autores a
                                     WHERE a.userid = p_userid ORDER BY a.desde DESC, a.autorid DESC LIMIT 1) u
                      WHERE u.nome = coalesce(n.nome, n.email, 'sem nome') AND u.email IS NOT DISTINCT FROM n.email)
$$;
REVOKE ALL ON FUNCTION public.registrar_autor(uuid) FROM public, anon, authenticated;

-- "Nome (e-mail)" de quem era o login naquele momento. Interna.
CREATE OR REPLACE FUNCTION public.autor_em(p_userid uuid, p_em timestamptz)
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT CASE WHEN a.email IS NULL OR a.email = a.nome THEN a.nome ELSE a.nome || ' (' || a.email || ')' END
    FROM public.autores a
   WHERE a.userid = p_userid
   ORDER BY (a.desde <= coalesce(p_em, now())) DESC,   -- o nome que valia naquela hora
            CASE WHEN a.desde <= coalesce(p_em, now()) THEN a.desde END DESC,
            a.desde, a.autorid DESC
   LIMIT 1
$$;
REVOKE ALL ON FUNCTION public.autor_em(uuid, timestamptz) FROM public, anon, authenticated;

-- Quando o nome muda: login novo, e-mail, nome da pessoa (colaborador) ou da
-- loja (tablet).
CREATE OR REPLACE FUNCTION public.autor_mudou()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE u uuid;
BEGIN
  IF TG_TABLE_NAME = 'users' THEN
    PERFORM public.registrar_autor(NEW.id);
  ELSIF TG_TABLE_NAME = 'contasusuarios' THEN
    PERFORM public.registrar_autor(NEW.userid);
  ELSIF TG_TABLE_NAME = 'funcionarios' THEN
    FOR u IN SELECT cu.userid FROM public.contasusuarios cu
              WHERE cu.contaid = NEW.contaid AND cu.funcionarioid = NEW.funcionarioid LOOP
      PERFORM public.registrar_autor(u);
    END LOOP;
  ELSIF TG_TABLE_NAME = 'lojas' THEN
    FOR u IN SELECT cu.userid FROM public.contasusuarios cu
              WHERE cu.contaid = NEW.contaid AND cu.lojaid = NEW.lojaid LOOP
      PERFORM public.registrar_autor(u);
    END LOOP;
  END IF;
  RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION public.autor_mudou() FROM public, anon, authenticated;

DROP TRIGGER IF EXISTS contasusuarios_autor ON public.contasusuarios;
CREATE TRIGGER contasusuarios_autor AFTER INSERT ON public.contasusuarios
  FOR EACH ROW EXECUTE FUNCTION public.autor_mudou();
DROP TRIGGER IF EXISTS stgame_autor ON auth.users;
CREATE TRIGGER stgame_autor AFTER UPDATE ON auth.users
  FOR EACH ROW WHEN (NEW.email IS DISTINCT FROM OLD.email)
  EXECUTE FUNCTION public.autor_mudou();
DROP TRIGGER IF EXISTS funcionarios_autor ON public.funcionarios;
CREATE TRIGGER funcionarios_autor AFTER UPDATE OF nomecompleto ON public.funcionarios
  FOR EACH ROW WHEN (NEW.nomecompleto IS DISTINCT FROM OLD.nomecompleto)
  EXECUTE FUNCTION public.autor_mudou();
DROP TRIGGER IF EXISTS lojas_autor ON public.lojas;
CREATE TRIGGER lojas_autor AFTER UPDATE OF nome ON public.lojas
  FOR EACH ROW WHEN (NEW.nome IS DISTINCT FROM OLD.nome)
  EXECUTE FUNCTION public.autor_mudou();

-- Todo login que já existe ganha o nome de agora, valendo desde que foi
-- criado (o nome de antes disso ninguém guardou).
INSERT INTO public.autores (contaid, userid, nome, email, desde)
SELECT n.contaid, cu.userid, coalesce(n.nome, n.email, 'sem nome'), n.email, coalesce(cu.criadoem, '-infinity')
  FROM public.contasusuarios cu
  CROSS JOIN LATERAL public.nome_do_login_agora(cu.userid) n
 WHERE NOT EXISTS (SELECT 1 FROM public.autores a WHERE a.userid = cu.userid);

