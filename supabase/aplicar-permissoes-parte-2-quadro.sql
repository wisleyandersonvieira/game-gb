                     JOIN public.contas c ON c.contaid = cu.contaid AND c.status = 'ativa'
                    WHERE cu.userid = auth.uid() AND cu.papel = 'gerente'))
$$;
REVOKE ALL ON FUNCTION public.conta_do_gestor_editavel() FROM public, anon, authenticated;

