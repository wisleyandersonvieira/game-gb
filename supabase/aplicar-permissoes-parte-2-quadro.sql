CREATE OR REPLACE FUNCTION public.conta_do_gestor_editavel()
RETURNS integer
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT coalesce(public.minha_conta_editavel(),
                  (SELECT c.contaid
                     FROM public.contasusuarios cu
